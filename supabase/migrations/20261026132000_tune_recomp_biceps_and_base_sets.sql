-- Экземпляры: a8f0c610 (195b3d79), b7c1d920 (43f5a91c), c9d3e430 (6416429a)
--
-- 1. Повторы базы в объёмной фазе возвращены к документу:
--      жим штанги лежа 8-12 -> 6-10, приседания 8-10 -> 6-10.
--    Это отмена двух моих отступлений: в исходном плане там 4x6-10.
--
-- 2. Бицепс: «Подъем штанги на бицепс стоя» +1 подход во всех рабочих фазах
--    (3/3/2 -> 4/4/3), разгрузочная фаза не тронута (там 2).
--    Причина: в истории аккаунта 6416429a 7,9 прямых подходов бицепса в неделю,
--    план давал 6; стало 7 — на уровне его фактической работы.
--
-- 3. База в силовых фазах возвращена к 4 подходам (было 3):
--    день1 поз1 тяга верхнего блока, день1 поз2 тяга штанги в наклоне,
--    день2 поз1 жим лежа, день2 поз2 жим гантелей на наклонной,
--    день3 поз1 присед, день3 поз2 жим ногами, день3 поз4 румынская.
--    Семь многосуставных позиций; памповая изоляция (махи, обратные разведения,
--    носки) и подсобка (тяга гантели, пуловер, блок на трицепс, пресс)
--    остаются срезанными — рост идёт весом, а не объёмом.
--
-- Итог по недельным подходам: 92 / 78 / 74 / 51 (было 91 / 70 / 66 / 51).
-- Убывание по фазам сохранено, разгрузка = -44,6% к первой фазе.
-- Записанных тренировок у экземпляров на момент правки нет -> снимки занятий
-- синхронизировать не нужно.
--
-- Правка идёт по (номер фазы, номер дня, позиция) с проверкой имени упражнения:
-- если имя не совпало, строка не меняется, а счётчики ниже это покажут.
-- ============================================================================

-- === 1. повторы базы в фазе 1 ==============================================
with tgt as (
  select pe.id, ph.phase_number, pd.day_number, pe.position, pe.exercise_name
    from program_phases ph
    join program_days pd      on pd.phase_id = ph.id
    join program_exercises pe on pe.program_day_id = pd.id
   where ph.program_id in ('a8f0c610-0000-4000-8000-000000000001',
                           'b7c1d920-0000-4000-8000-000000000001',
                           'c9d3e430-0000-4000-8000-000000000001')
)
update program_exercises pe
   set reps_range = '6-10'
  from tgt t
 where pe.id = t.id
   and t.phase_number = 1
   and ((t.day_number = 2 and t.position = 1 and t.exercise_name = 'Жим штанги лежа на горизонтальной скамье')
     or (t.day_number = 3 and t.position = 1 and t.exercise_name = 'Приседания со штангой на плечах'));

-- === 2. бицепс: штанга стоя +1 подход в рабочих фазах ======================
with tgt as (
  select pe.id, ph.phase_number, pd.day_number, pe.position, pe.exercise_name
    from program_phases ph
    join program_days pd      on pd.phase_id = ph.id
    join program_exercises pe on pe.program_day_id = pd.id
   where ph.program_id in ('a8f0c610-0000-4000-8000-000000000001',
                           'b7c1d920-0000-4000-8000-000000000001',
                           'c9d3e430-0000-4000-8000-000000000001')
)
update program_exercises pe
   set sets = pe.sets + 1
  from tgt t
 where pe.id = t.id
   and t.phase_number in (1, 2, 3)
   and t.day_number = 2
   and t.position = 7
   and t.exercise_name = 'Подъем штанги на бицепс стоя';

-- === 3. база: 4 подхода в фазах 2 и 3 ======================================
with tgt as (
  select pe.id, ph.phase_number, pd.day_number, pe.position, pe.exercise_name
    from program_phases ph
    join program_days pd      on pd.phase_id = ph.id
    join program_exercises pe on pe.program_day_id = pd.id
   where ph.program_id in ('a8f0c610-0000-4000-8000-000000000001',
                           'b7c1d920-0000-4000-8000-000000000001',
                           'c9d3e430-0000-4000-8000-000000000001')
)
update program_exercises pe
   set sets = 4
  from tgt t
 where pe.id = t.id
   and t.phase_number in (2, 3)
   and (t.day_number, t.position) in ((1, 1), (1, 2), (2, 1), (2, 2), (3, 1), (3, 2), (3, 4));

