-- Правка выложенной программы «Рекомпозиция — 3 дня, акцент грудь»
-- Три позиции уточнены владельцем 26.10.2026 после сверки с исходным документом:
--   1) «Тяга в хаммере поочерёдно каждой рукой» = изометрическая тяга в рычажном
--      тренажёре (тяга одной рукой поочерёдно), а не тяга гантели -> был взят
--      вариант с гантелью как «альтернатива из документа», это ошибка толкования;
--   2) «Пуловер широким хватом» = пуловер в блоке (Straight-Arm Pulldown),
--      а не штанга лёжа;
--   3) «Подъёмы на носки стоя в тренажёре» = «Подъем на носки стоя».
--
-- Затронуто 36 строк program_exercises: 3 позиции x 4 фазы x 3 экземпляра
-- (a8f0c610 = 195b3d79, b7c1d920 = 43f5a91c, c9d3e430 = 6416429a).
-- Подходы, повторы, отдых, intensity, target_rpe и progression_policy НЕ меняются.
-- Тренировок у этих программ на момент правки 0 -> снимков занятий, которые
-- пришлось бы синхронизировать, нет (иначе нужен был порядок: сначала правка
-- текущей тренировки, потом sync).
--
-- Имена резолвятся по каталогу, без захардкоженных uuid упражнений.
-- «Изометрическая тяга в рычажном тренажере» и «Подъем на носки стоя» —
-- строки со статусом «на проверке»: до правки их было 6 distinct / 24 строки,
-- после правки 8 distinct / 32 строки (прежние две позиции были «проверены»).
-- ============================================================================

update program_exercises pe
   set exercise_id = x.id, exercise_name = x.name
  from exercises x
 where x.name = 'Изометрическая тяга в рычажном тренажере'
   and pe.exercise_name = 'Тяга гантели одной рукой в наклоне'
   and exists (select 1 from program_days pd
                where pd.id = pe.program_day_id
                  and pd.program_id in ('a8f0c610-0000-4000-8000-000000000001',
                                        'b7c1d920-0000-4000-8000-000000000001',
                                        'c9d3e430-0000-4000-8000-000000000001'));

update program_exercises pe
   set exercise_id = x.id, exercise_name = x.name
  from exercises x
 where x.name = 'Пуловер в блоке (Straight-Arm Pulldown)'
   and pe.exercise_name = 'Пуловер со штангой лежа (согнутые руки)'
   and exists (select 1 from program_days pd
                where pd.id = pe.program_day_id
                  and pd.program_id in ('a8f0c610-0000-4000-8000-000000000001',
                                        'b7c1d920-0000-4000-8000-000000000001',
                                        'c9d3e430-0000-4000-8000-000000000001'));

update program_exercises pe
   set exercise_id = x.id, exercise_name = x.name
  from exercises x
 where x.name = 'Подъем на носки стоя'
   and pe.exercise_name = 'Подъем на носки в тренажере для жима ногами'
   and exists (select 1 from program_days pd
                where pd.id = pe.program_day_id
                  and pd.program_id in ('a8f0c610-0000-4000-8000-000000000001',
                                        'b7c1d920-0000-4000-8000-000000000001',
                                        'c9d3e430-0000-4000-8000-000000000001'));

