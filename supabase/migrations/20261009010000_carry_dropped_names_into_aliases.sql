-- ILL-5 (до-миграция): имена удалённых дублей должны остаться в поиске.
--
-- Шаг 4 дедупликации переносил в оставляемую строку массив `aliases` удалённой, но
-- НЕ её `name`. Для 11 из 17 пар это случайно не заметено (у большинства позиций
-- алиасы равны паре [name, name_eng] — находка CAT-Q8), но для 6 пар имя удалённой
-- строки пропало из каталога целиком: запрос «румынская тяга со штангой» или
-- «выпады со штангой на плечах» больше не находит оставленную позицию, а выдаёт
-- соседние варианты. Это ровно тот случай, который владелец описал как «дополнить
-- карточку при необходимости».
--
-- Имена взяты из exercises_removed_archive (снимок до удаления), поэтому источник
-- достоверный; список пар даёт запрос в конце файла.
--
-- Реверс: удалить добавленные значения из aliases (каждое перечислено в VALUES ниже).
-- ============================================================================

UPDATE public.exercises k
SET aliases = (SELECT array_agg(DISTINCT x ORDER BY x)
               FROM unnest(coalesce(k.aliases, '{}'::text[]) || ARRAY[v.drop_name]) x)
FROM (VALUES
  ('b84d37c1-d58e-470f-857b-fbbb74c12637'::uuid, 'Выпады со штангой на плечах'),
  ('2f6cf819-31a7-4225-9da5-f4e5db783c06', 'Жим плеч в рычажном тренажёре'),
  ('85dd4a2c-1d51-4e21-a237-95c843f54d5a', 'Обратные разведения в тренажере'),
  ('d8a63040-8208-40f8-881c-e2c198c6187b', 'Ролик для пресса'),
  ('be4f02cc-6958-4592-8728-820569b8710d', 'Румынская тяга со штангой'),
  ('d141a282-3f8b-40aa-91d0-9c89d56d3667', 'Сгибание рук с гантелями нейтральным хватом (молот)')
) AS v(keep_id, drop_name)
WHERE k.id = v.keep_id
  AND NOT (coalesce(k.aliases, '{}'::text[]) @> ARRAY[v.drop_name]);   -- идемпотентность

