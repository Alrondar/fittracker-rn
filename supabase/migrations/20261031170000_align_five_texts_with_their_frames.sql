    if n <> 5 then
        raise exception 'align texts aborted: строк с ожидаемыми именами % — ждали 5', n;
    end if;

    select count(*) into n from public.equipment where name = 'Партнер';
    if n <> 1 then
        raise exception 'align texts aborted: снаряд «Партнер» найден в количестве % — ждали 1', n;
    end if;

    select count(*) into n from public.exercise_equipment ee
      join public.equipment e on e.id = ee.equipment_id
     where ee.exercise_id = '80d2ad1e-2cd6-464b-b1d8-a1b10ed09821'
       and e.name = 'Партнер';
    if n <> 0 then
        raise exception 'align texts aborted: «Партнер» уже привязан к «ослику»';
    end if;

    select count(*) into n from public.injury_exercise_warnings
     where exercise_id = '80d2ad1e-2cd6-464b-b1d8-a1b10ed09821';
    if n <> 1 then
        raise exception 'align texts aborted: предупреждений по пояснице у «ослика» % — ждали 1 (перенос не состоялся?)', n;
    end if;
end
$$;

