declare
    n bigint;
begin
    select count(*) into n from public.exercises
      where (id = '38d6554c-3551-411b-8f08-fbac0f612765' and name = 'Концентрированный подъем штанги на бицепс сидя')
         or (id = 'faecbdb7-b89c-41d3-816c-b7c7df073e4f'  and name = 'Подъем на бицепс на скамье Скотта')
