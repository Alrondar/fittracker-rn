-- ============================================================================
-- CAT-1b (мелочь): грамматическая правка текста техники Rotational_Romanian_Deadlift.
--
-- В CAT-1 в `technique` ушло «Выполняйте румынская тяга с одной гантелью» —
-- имя собственное движения стояло в именительном падеже вместо винительного.
-- Текст карточки читается пользователю как есть (L2 «Техника»), правится только он:
-- смысл упражнения, мышцы, снаряд и кадры не затрагиваются.
--
-- Реверс:
--   UPDATE public.exercises
--   SET technique = replace(technique, 'Выполняйте румынскую тягу с одной гантелью',
--                           'Выполняйте румынская тяга с одной гантелью')
--   WHERE name_eng = 'Rotational Romanian Deadlift';
--
-- Ожидаемый эффект ровно на одну строку; проверено SELECT-ом до и после.
-- ============================================================================

UPDATE public.exercises
SET technique = replace(
  technique,
  'Выполняйте румынская тяга с одной гантелью',
  'Выполняйте румынскую тягу с одной гантелью'
)
WHERE name_eng = 'Rotational Romanian Deadlift'
  AND technique LIKE '%Выполняйте румынская тяга с одной гантелью%';
