-- Две строки переписаны под свои кадры, а не наоборот. Решение владельца 31.10:
-- «Выход силой на турнике — переписать под кольца», «Внешняя ротация плеча в
-- нижнем блоке — переписать под изображения».

--
-- Почему кадр здесь первичнее текста.
--   `8820ed15` — на обоих кадрах `Muscle_Up` спортсмен работает на гимнастических
--   кольцах (видны подвесы и кольца), ложный хват и разворот колец наружу. Турника
--   в кадре нет. Строки «выход силой на кольцах» в каталоге не было: есть
--   `d214102c` «Выход силой с раскачкой» (Kipping Muscle Up) и `3205874e`
--   «Отжимания на кольцах» (Ring Dips) — другие движения, дубля не получается.
--   `cb315b69` — на кадрах `External_Rotation` спортсмен лежит на боку на скамье,
--   локоть опирается о бедро, в верхней руке гантель. Это законный отдельный
--   вариант наружной ротации (реабилитационный стандарт), а не вариант блока:
--   существующие `4508a86b` «в кроссовере» и `47e52092` «с резинкой» остаются как
--   были, коллизии нет.
--
-- Границы и ориентиры сверены с внешними описаниями: e3rehab (вращательная
-- манжета, наружная ротация лёжа на боку: локоть прижат, движение только в
-- плечевом суставе, вес минимальный), разборы выхода на кольцах (ложный хват,
-- тяга к низу груди, наклон вперёд, разворот колец, жим в упор).
--
-- Blast radius. Две строки `exercises`: `name`, `aliases`, `technique`,
-- `settings`, `updated_at`, и `search_text` (пересобирается ШАГОМ 3, потому что
-- правка `name` будит `trg_fill_search_text`, пишущий короткую формулу).
-- `status`, мышцы, теги, категория, `media_url` и кадры не меняются.
-- Занятость обеих строк — 0 слотов в программах и 0 строк в тренировках
-- (проверяется guard'ом), так что снимки `exercise_name` в существующих
-- программах трогать нечего.
--
-- ПРОВЕРКИ до (замер 31.10):
