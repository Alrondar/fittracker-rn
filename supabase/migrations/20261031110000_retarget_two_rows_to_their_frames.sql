--   select count(*) from public.exercises
--    where lower(name) in ('внешняя ротация плеча лёжа на боку с гантелью','выход силой на кольцах');  -- 0
--   select count(*) from public.program_exercises
--    where exercise_id in ('cb315b69-45bf-4e8b-9f98-9dca7bf2be0d','8820ed15-08d7-49dd-8bf9-b2955ca7199c');  -- 0

-- ШАГ 1. GUARD.
do $$
declare
    n bigint;
begin
    select count(*) into n from public.exercises
     where (id = 'cb315b69-45bf-4e8b-9f98-9dca7bf2be0d'
              and name = 'Внешняя ротация плеча в нижнем блоке' and status = 'approved')
        or (id = '8820ed15-08d7-49dd-8bf9-b2955ca7199c'
              and name = 'Выход силой на турнике' and status = 'approved');
    if n <> 2 then
        raise exception 'retarget aborted: строк с ожидаемыми именами найдено % — ждали 2', n;
    end if;

    select count(*) into n from public.exercises
     where lower(name) in ('внешняя ротация плеча лёжа на боку с гантелью', 'выход силой на кольцах');
    if n <> 0 then
        raise exception 'retarget aborted: новое имя уже занято, строк %', n;
    end if;

    select count(*) into n from public.program_exercises
     where exercise_id in ('cb315b69-45bf-4e8b-9f98-9dca7bf2be0d',
                           '8820ed15-08d7-49dd-8bf9-b2955ca7199c');
    if n <> 0 then
        raise exception 'retarget aborted: строки заняты в программах, слотов % — перечитать', n;
    end if;

    raise notice 'guard ok: две строки на месте, имена свободны, занятость нулевая';
end
$$;

-- ШАГ 2. Имена, псевдонимы и тексты. Прежние имена уходят в `aliases`, чтобы
-- поиск по старой формулировке не пропал.
update public.exercises
   set name = 'Внешняя ротация плеча лёжа на боку с гантелью',
       aliases = (select array_agg(distinct x) from unnest(
                    coalesce(aliases, '{}') || array['Внешняя ротация плеча в нижнем блоке']) x),
       technique = 'Ляг на бок на горизонтальную скамью. Нижнюю руку согни и упирайся предплечьем в бедро, верхним плечом прижмись к корпусу так, чтобы локоть встал под 90° и оставался там до конца подхода. В верхней руке держи лёгкую гантель, кисть — в продолжении предплечья. На выдохе разверни предплечье вверх, к потолку, не отрывая локоть от корпуса и не отводя плечо назад: ориентир — 60–70° подъёма, дальше работает не манжета, а задняя дельта. Задержись вверху на секунду и на вдохе так же медленно верни предплечье в исходное положение. Перевернись на другой бок и повтори другой рукой.',
       settings = 'Горизонтальная скамья и лёгкая гантель: 1–2 кг для первого раза, дальше до 4 кг. Локоть всю амплитуду лежит на бедре и прижат к корпусу, движение идёт только в плечевом суставе. Боль в глубине плеча — сигнал прекратить подход, а не дожимать амплитуду.'
 where id = 'cb315b69-45bf-4e8b-9f98-9dca7bf2be0d';

update public.exercises
   set name = 'Выход силой на кольцах',
       aliases = (select array_agg(distinct x) from unnest(
                    coalesce(aliases, '{}') || array['Выход силой на турнике']) x),
       technique = 'Возьмись за кольца ложным хватом: запястье ложится поверх кольца, большой и указательный пальцы охватывают его сзади, кольцо лежит на основании ладони. Встань на подставку так, чтобы кольца оказались на уровне груди, выпрями руки и разведи их в стороны, стабилизировав от раскачивания. Сними ноги с подставки — это исходное положение, вис на прямых руках. Подтянись так, чтобы локти шли назад-вниз вдоль корпуса, а грудь поднималась к кольцам; одновременно кольца разворачиваются наружу и уходят к бёдрам. Доведи грудь до уровня колец и наклонись вперёд, перенося запястья поверх колец. Перекатись через них грудью и выжми себя вверх до прямых рук в упоре, кольца у бёдер. Задержись в упоре без раскачивания и так же контролируемо вернись в вис, развернув кольца обратно.',
       settings = 'Гимнастические кольца на высоте, позволяющей встать на подставку и свободно повиснуть; под ногами подставка или мат. Ложный хват отрабатывается отдельно: вис на ложном хвате 20–30 с и упор на кольцах на прямых руках. Брать в работу после 8–10 чистых подтягиваний и уверенного упора на кольцах; при боли в запястье ложный хват исключается.'
 where id = '8820ed15-08d7-49dd-8bf9-b2955ca7199c';

-- ШАГ 3. `search_text` после правки `name` пересобрать полной формулой:
-- `trg_fill_search_text` пишет короткую (без мышц, снаряда, тегов и категории).
update public.exercises x
   set search_text = lower(replace(concat_ws(' ',
        x.name, x.name_eng, x.short_name,
        array_to_string(x.aliases, ' '),
        array_to_string(x.primary_muscles, ' '),
        array_to_string(x.secondary_muscles, ' '),
        (select string_agg(e.name, ' ' order by e.name)
           from public.exercise_equipment ee
           join public.equipment e on e.id = ee.equipment_id
          where ee.exercise_id = x.id),
        array_to_string(x.tags, ' '),
        x.category), 'ё', 'е'))
 where x.id in ('cb315b69-45bf-4e8b-9f98-9dca7bf2be0d',
                '8820ed15-08d7-49dd-8bf9-b2955ca7199c');

