// src/lib/queryPolicy.ts
// PERF-10 (01.10): единый владелец тиров свежести React Query (CLAUDE.md
// «один факт — один владелец»; до этого ~30 мест дублировали литералы
// 2м/5м/10м/1ч/Infinity/30с в четырёх форматах).
//
// Глобальный дефолт (_layout.tsx) — Q.SLOW.staleTime + retry 1. Хуку, которому
// нужен дефолтный тир, лучше вообще не указывать staleTime; Q.SLOW используется
// явно там, где значение должно читаться из одного места (пре-фетч обязан
// совпадать с потребителем) и в комментариях-обоснованиях.
//
// Про gcTime: дефолт RQ v5 — 5 мин. Это значит, что staleTime: Infinity БЕЗ
// gcTime ничего не «хранит навсегда»: кэш уничтожается через 5 минут после
// отписки и при следующем монтировании идёт сетевой запрос (находка PERF-10).
// Поэтому тир STATIC носит пару staleTime+gcTime, а DAILY — gcTime ≥ staleTime.
export const MINUTE = 60 * 1000;
export const HOUR = 60 * MINUTE;
export const DAY = 24 * HOUR;

export const Q = {
  /**
   * Справочник/статика: упражнения, словари фильтров, правила предупреждений,
   * противопоказания. Меняется только миграциями на сервере.
   * gcTime = сутки: на практике кэш живёт до перезапуска приложения, но не
   * накапливается бесконечно (per-exercise ключей много).
   */
  STATIC: { staleTime: Infinity, gcTime: DAY },
  /** Раз в день: чек-ины (recovery/readiness), настройки цикла. */
  DAILY: { staleTime: HOUR, gcTime: DAY },
  /** Базовый тир аналитики — тот же, что глобальный дефолт. */
  SLOW: { staleTime: 5 * MINUTE },
  /**
   * Списки, где часть мутаций не покрыта сквозной инвалидацией (программы,
   * рекорды, журнал питания): короче дефолта, чтобы правки других сессий не
   * «вставали» надолго.
   */
  FAST: { staleTime: 2 * MINUTE },
} as const;
