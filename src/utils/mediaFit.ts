// src/utils/mediaFit.ts
// MED-FIT (08.10): как показывать кадр техники, чтобы не было НИ боковых полей,
// НИ обрезки.
//
// Исходный дефект: `TechniqueMediaSlider` рисовал всё `contentFit="cover"` в боксе
// фиксированной высоты (190 в карточках / 220 на странице упражнения) при плавающей
// ширине. По замеру JPEG-заголовков случайной выборки 70 упражнений каталога (все 821
// медиа — `raw.githubusercontent.com/yuhonas/free-exercise-db`) там 93% кадров 3:2
// (850×567/569, 750×500) и ~7% вертикальных 2:3 (850×1275, 500×750). Cover резал
// горизонтальные на 13–32% (сильнее на широком окне — высота же константа), а
// вертикальные на 61–70%: у стоящего человека не оставалось ни головы, ни ног.
//
// Первый вариант (contain по размытой подложке) обрезку убрал, но дал боковые поля —
// владелец отверг: «изображения должны отображаться без боковых рамок». Поля и обрезка
// — две половины одной задачи: при фиксированном боксе картинка либо не влезает
// целиком, либо не заполняет его. Значит подстраивать надо бокс.
//
// `mediaBoxHeight` даёт высоту = ширина / пропорции картинки, в пределах
// [minHeight, MAX_BOX_H_RATIO × ширина]. При потолке 1.5 весь измеренный каталог
// (от 2:3 до 3:2) встаёт точно по своим пропорциям — без полей и без потерь.
// Формула отделена от компонента, чтобы гонять её на реальных размерах через npx tsx.

/** Потолок высоты бокса как множитель ширины. 1.5 = кадр 2:3 показывается целиком. */
export const MAX_BOX_H_RATIO = 1.5;

/**
 * Высота бокса слайдера под конкретный кадр.
 * minHeight — прежняя фиксированная высота (190/220): ниже неё не уходим, чтобы
 * очень широкие кадры не превращались в полоску. Пока размеры картинки или ширина
 * бокса неизвестны (изображение не загружено / onLayout не пришёл) — minHeight,
 * то есть поведение не отличается от прежнего.
 */
export function mediaBoxHeight(
  boxW: number,
  imgW: number,
  imgH: number,
  minHeight: number
): number {
  if (!boxW || !imgW || !imgH) return minHeight;
  const ideal = boxW * (imgH / imgW);
  return Math.min(Math.max(ideal, minHeight), boxW * MAX_BOX_H_RATIO);
}

/**
 * Диагностика: долю кадра, которую `cover` отсек бы у этого изображения в этом боксе
 * (0 — пропорции совпали, →1 — отрезано почти всё). Нужна tsx-харнесу, чтобы видеть,
 * сколько реально теряется до и после перехода на адаптивную высоту.
 */
export function coverCropLoss(imgW: number, imgH: number, boxW: number, boxH: number): number {
  if (!imgW || !imgH || !boxW || !boxH) return 0;
  const imgRatio = imgW / imgH;
  const boxRatio = boxW / boxH;
  return 1 - Math.min(imgRatio, boxRatio) / Math.max(imgRatio, boxRatio);
}
