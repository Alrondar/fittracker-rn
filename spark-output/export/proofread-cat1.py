# -*- coding: utf-8 -*-
"""CAT-1: вычитка пользовательских текстов миграции перед применением.

Правит только содержательные строки technique/benefits/risks/settings в
supabase/migrations/20261008133000_seed_exercises_glute_hinge_delt.sql.
После замены проверяет баланс кавычек вне комментариев — именно так был пойман
обрывок кавычки в массиве алиасов.
"""
import io

P = 'supabase/migrations/20261008133000_seed_exercises_glute_hinge_delt.sql'

REPL = [
    ('на низком подставке', 'на низкой подставке'),
    ('за счёт движения бедер вперед', 'за счёт движения бёдер вперёд'),
    ('Проще контрольной румынки на одной ноге и строже, чем обычная.',
     'Проще румынки на одной ноге и строже обычной.'),
    ('нижними трапециеями', 'нижними трапециями'),
    ('Скамьё под углом', 'Скамья под углом'),
    ('сужает подкромиальное пространство', 'сужает подкромиальное пространство'),
    ('Удобна при разнице силы плеч.', 'Удобен при разнице силы плеч.'),
    ('Удобна для дроп-сетов', 'Подходит для дроп-сетов'),
    ('Округление спины поднимает нагрузку', 'Округление спины увеличивает нагрузку'),
    ('которых нет в парной тяге', 'которых нет в обычной румынке'),
    ('Разогните бедра, поднимая таз', 'Разогните бёдра, поднимая таз'),
    ('Разогните бедра, отжимая подушку', 'Разогните бёдра, отжимая подушку'),
]

s = io.open(P, encoding='utf-8').read()
for a, b in REPL:
    if a not in s:
        print('MISS:', a)
    s = s.replace(a, b)

io.open(P, 'w', encoding='utf-8', newline='').write(s)

bad = []
for i, line in enumerate(io.open(P, encoding='utf-8'), 1):
    code = '' if line.lstrip().startswith('--') else line.split('--')[0]
    if code.count("'") % 2:
        bad.append(i)
print('небаланс кавычек по строкам:', bad)
print('остатки:', [a for a, _ in REPL if a in io.open(P, encoding='utf-8').read()])
